let native: LangCode = 'en';
export const setUiLang = (l: LangCode) => { native = l; document.documentElement.lang = l; };
export const uiLang = () => native;

export function t(key: string, vars?: Record<string, string | number>, lang: LangCode = native): string {
  const entry = STR[key];
  let s = entry ? entry[lang] ?? entry.en ?? key : key;
  if (vars) for (const k in vars) s = s.split(`{${k}}`).join(String(vars[k]));
  return s;
}

/** Pick a language from an LText-like object, falling back to English. */
export const pick = (txt: Record<string, string> | undefined, lang: LangCode = native) => (txt ? txt[lang] ?? txt.en ?? '' : '');
